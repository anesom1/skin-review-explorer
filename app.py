# Define a multi-aspect classifier model using DistilBERT as the base model. The model has separate linear heads for each aspect to predict sentiment (positive, negative, not mentioned).
# NOTE: See the notebook "sentiment_analysis_for_skincare_phase3.ipynb" or "sentiment_analysis_for_skincare_phase4.ipynb" for details on the model architecture and training process.
class MultiAspectClassifier(nn.Module):
    def __init__(self, model_name, aspects, num_classes=3, dropout=0.3):
        super().__init__()
        self.bert = DistilBertModel.from_pretrained(model_name)
        self.aspects = aspects
        hidden_size = self.bert.config.hidden_size

        self.dropout = nn.Dropout(dropout)
        self.heads = nn.ModuleDict({
            aspect: nn.Linear(hidden_size, num_classes) for aspect in aspects
        })

    def forward(self, input_ids, attention_mask):
        outputs = self.bert(input_ids=input_ids, attention_mask=attention_mask)
        pooled = outputs.last_hidden_state[:, 0]  # token [CLS]
        pooled = self.dropout(pooled)
        logits = {aspect: self.heads[aspect](pooled) for aspect in self.aspects}
        return logits

# Define the aspects and the mapping from prediction indices to sentiment labels 
ASPECTS = ["texture", "scent", "breakouts", "irritation", "efficacy", "packaging", "value"]
ID2LABEL = {0: "Not mentioned", 1: "Positive", 2: "Negative"}

# Download model weights from Hugging Face Hub if not already present locally. Use Streamlit's caching to avoid repeated downloads.
@st.cache_resource
def download_model_from_hf():
    model_path = "aspect_sentiment_model_final.pt"
    if not os.path.exists(model_path):
        with st.spinner("Downloading AI model weights from Hugging Face..."):
            hf_hub_download(
                repo_id="anesom/skincare-review-model",
                filename="aspect_sentiment_model_final.pt",
                local_dir="."
            )
    return model_path

# Download the dataset from Hugging Face Hub if not already present locally. Use Streamlit's caching to avoid repeated downloads.
@st.cache_data
def download_data_from_hf():
    csv_path = "skincare_reviews_with_predictions.csv"
    if not os.path.exists(csv_path):
        with st.spinner("Downloading dataset from Hugging Face..."):
            hf_hub_download(
                repo_id="anesom/skincare-review-dataset",
                filename="skincare_reviews_with_predictions.csv",
                repo_type="dataset",
                local_dir="."
            )
    return csv_path

# Load the model and tokenizer, and set the device to CPU (as Streamlit Cloud uses CPU). Use Streamlit's caching to avoid reloading the model on every interaction.
@st.cache_resource
def load_model_and_tokenizer():
    device = torch.device("cpu")  # Streamlit Cloud uses CPU
    model_name = "distilbert-base-uncased"
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    
    model = MultiAspectClassifier(model_name, ASPECTS).to(device)
    checkpoint = torch.load(download_model_from_hf(), map_location=device)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()
    return model, tokenizer, device

