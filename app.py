    # Apply filters
    # -----------------------------
    # Filter the dataset based on the selected product and skin type. If no reviews match the filters, display a warning message and stop further execution.
    filtered = df[df[PRODUCT_COL] == selected_product].copy()

    if selected_skin != "All":

        if selected_skin == "Unknown only":
            filtered = filtered[
                filtered[SKIN_COL] == "Unknown"
            ]

        else:

            mask = filtered[SKIN_COL].fillna("").str.lower() == selected_skin.lower()

            if include_unknown:
                mask = mask | (filtered[SKIN_COL] == "Unknown")

            filtered = filtered[mask]

    if filtered.empty:
        st.warning(
            f"No reviews for **{selected_product}** match the skin type filter "
            f"'{selected_skin}'. Try selecting 'All' or a different skin type."
        )
        st.stop()

    # -----------------------------
    # Product overview
    # -----------------------------
    # Display an overview of the selected product, including the number of reviews, 
    # average rating, brand, category, and the number of reviews with unknown skin types. 
    # Use Streamlit's metric components to display these values in a visually appealing way.
    st.header(selected_product)

    if selected_skin != "All":
        filter_label = selected_skin if selected_skin == "Unknown only" else f"{selected_skin} skin"
        if selected_skin != "Unknown only" and include_unknown:
            filter_label += " (+ Unknown)"
        st.caption(f"Filtered to: {filter_label}")

