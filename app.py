    # Load data
    # -----------------------------

    @st.cache_data
    def load_data():
        return pd.read_csv(download_data_from_hf(), low_memory=False)

    df = load_data()

    @st.cache_data
    def get_product_names(df):
        return df["product_name"].dropna().sort_values().unique().tolist()

    @st.cache_data
    def get_product_brand_map(df):
        return (
            df.dropna(subset=["product_name"])
            .drop_duplicates(subset="product_name")
            .set_index("product_name")["brand_name"]
            .to_dict()
        )

    # -----------------------------
    # Column names
    # -----------------------------
    # Define the column names used in the dataset for product name, skin type, and rating. Also, create a list of prediction columns for each aspect.
    PRODUCT_COL = "product_name"
    SKIN_COL = "skin_type"
    RATING_COL = "rating"

    PRED_COLUMNS = [f"{a}_pred" for a in ASPECTS]

    # -----------------------------
    # Sidebar filters
    # -----------------------------
    # Create sidebar filters for selecting a product and filtering by skin type. Use Streamlit's session state to remember the last selected product across interactions.
    st.sidebar.header("Filters")
    # Get unique product names and create a mapping from product name to brand name for display in the selectbox.
    product_names = get_product_names(df)
    product_brand_map = get_product_brand_map(df)
    # Use session state to remember the last selected product and the version of the product key to handle changes in the selectbox.
    if "product_key_version" not in st.session_state:
        st.session_state.product_key_version = 0
    if "last_selected_product" not in st.session_state:
        st.session_state.last_selected_product = product_names[0]
    # Define a callback function to update the last selected product and increment the product key version when the selectbox value changes.
    def _on_product_change():
        current_key = f"product_search_{st.session_state.product_key_version}"
        st.session_state.last_selected_product = st.session_state[current_key]
        st.session_state.product_key_version += 1
    # Determine the index of the last selected product in the product names list to set the default selection in the selectbox.
    current_index = (
        product_names.index(st.session_state.last_selected_product)
        if st.session_state.last_selected_product in product_names
        else 0
    )
    # Create a selectbox in the sidebar for searching and selecting a product. The selectbox displays the brand name and product name, and calls the callback function when the selection changes.
    selected_product = st.sidebar.selectbox(
        "Search product",
        product_names,
        index=current_index,
        format_func=lambda name: f"{product_brand_map.get(name, 'Unknown brand')} — {name}",
        key=f"product_search_{st.session_state.product_key_version}",
        on_change=_on_product_change,
    )
