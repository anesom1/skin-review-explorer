# -----------------------------
# Tab 2: Live Review Analyzer (AI Model)
# ----------------------------- 
# Create a tab for users to input a new skincare review and analyze it using the fine-tuned DistilBERT model. 
# The model predicts the sentiment (Positive, Negative, Not mentioned) for each aspect in real-time.
with tab2:
    st.subheader("🔮 Analyze a New Review")
    st.write("Type or paste a skincare review below to test the fine-tuned model and see real-time aspect predictions.")
    
    user_review = st.text_area(
        "Review text:",
        placeholder="e.g., The texture of this cream is wonderfully light and pleasant, but unfortunately, the scent is too strong and it caused some irritation."
    )
    
    if st.button("Analyze Review", type="primary"):
        if not user_review.strip():
            st.warning("Please enter a review text first.")
        else:
            with st.spinner("Loading model and running inference..."):
                model, tokenizer, device = load_model_and_tokenizer()
                
                encoding = tokenizer(
                    user_review,
                    truncation=True,
                    padding="max_length",
                    max_length=256,
                    return_tensors="pt"
                )
                
                input_ids = encoding["input_ids"].to(device)
                attention_mask = encoding["attention_mask"].to(device)
                
                with torch.no_grad():
                    logits = model(input_ids, attention_mask)
                    predictions = {}
                    for aspect in ASPECTS:
                        pred_idx = torch.argmax(logits[aspect], dim=1).item()
                        predictions[aspect] = ID2LABEL[pred_idx]
                
                st.success("Analysis complete!")
                
                res_data = []
                for aspect, sentiment in predictions.items():
                    emoji = "⚪"
                    if sentiment == "Positive":
                        emoji = "🟢"
                    elif sentiment == "Negative":
                        emoji = "🔴"
                    res_data.append({"Aspect": aspect.capitalize(), "Predicted Sentiment": f"{emoji} {sentiment}"})
                
                st.table(pd.DataFrame(res_data))