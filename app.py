    skin_options = [
        "All",
        "Dry",
        "Oily",
        "Combination",
        "Normal",
        "Unknown only"
    ]
    # Create a selectbox in the sidebar for filtering by skin type, with options for "All", specific skin types, and "Unknown only". Also, create a checkbox to include or exclude reviews with unknown skin types in the analysis.
    selected_skin = st.sidebar.selectbox(
        "Skin type",
        skin_options
    )
    # Create a checkbox in the sidebar to include or exclude reviews with unknown skin types in the analysis. The default value is set to True (include unknown).
    include_unknown = st.sidebar.checkbox(
        "Include Unknown skin type",
        value=True
    )

